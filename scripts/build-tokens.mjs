// Turns the theme token files in tokens/ into CSS variables
// (src/styles/tokens.generated.css). Design Section 8.
// Skins are switched by setting data-skin on <html>; accents by data-accent;
// Chalk and Iron backgrounds by data-bg. Nothing else in the app holds a
// color or a font name.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const read = (p) => JSON.parse(readFileSync(join(root, 'tokens', p), 'utf8'));

export const TOKEN_NAMES = [
  'background', 'text', 'muted-text', 'line', 'border', 'surface', 'sheet', 'accent', 'on-accent',
  'secondary-accent', 'selected-fill', 'dial-fill', 'display-font', 'body-font', 'radius', 'radius-small',
  'shadow', 'heading-size', 'numeral-size',
];
export const EXTRA_NAMES = ['on-selected', 'display-weight', 'display-case'];

export function loadTokens() {
  const skins = readdirSync(join(root, 'tokens', 'skins')).filter((f) => f.endsWith('.json')).sort()
    .map((f) => read(join('skins', f)));
  return { skins, accents: read('accents.json'), backgrounds: read('backgrounds.json'), fixed: read('fixed.json') };
}

function validate({ skins }) {
  for (const s of skins) {
    const t = Object.keys(s.tokens).sort().join();
    if (t !== [...TOKEN_NAMES].sort().join()) throw new Error(`Skin ${s.id} must define exactly the ${TOKEN_NAMES.length} tokens`);
    if (Object.keys(s.extras).sort().join() !== [...EXTRA_NAMES].sort().join()) throw new Error(`Skin ${s.id} must define the three extras`);
  }
}

function value(name, v, fixed) {
  if (typeof v !== 'string') return String(v);
  const ref = v.match(/^\{(.+)\}$/);
  if (ref) return `var(--${ref[1]})`;
  if (name.endsWith('-font')) return `'${v}', ${fixed['font-fallbacks'][v] ?? 'sans-serif'}`;
  return v;
}

function block(selector, vars, fixed) {
  return `${selector} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${value(k, v, fixed)};`).join('\n')}\n}\n`;
}

export function buildCss() {
  const all = loadTokens();
  validate(all);
  const { skins, accents, backgrounds, fixed } = all;
  const chalk = skins.find((s) => s.id === 'chalk');
  let css = '/* Generated by scripts/build-tokens.mjs from tokens/. Do not edit by hand. */\n\n';
  css += block(':root', { 'overage-red': fixed['overage-red'] }, fixed);
  css += block(':root, [data-skin="chalk"]', { ...chalk.tokens, ...chalk.extras }, fixed);
  for (const s of skins.filter((s) => s.id !== 'chalk')) css += block(`[data-skin="${s.id}"]`, { ...s.tokens, ...s.extras }, fixed);
  for (const a of accents.accents) css += block(`[data-accent="${a.id}"]`, { accent: a.value, 'on-accent': accents['on-accent'] }, fixed);
  for (const b of backgrounds.backgrounds.filter((b) => Object.keys(b.tokens).length)) {
    const vars = { ...b.tokens };
    if (b.frame) vars['frame'] = b.frame;
    css += block(`[data-skin="${backgrounds.skin}"][data-bg="${b.id}"]`, vars, fixed);
  }
  // The record card always shows in Arcade, a finished workout in Liquid Color.
  return css;
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  writeFileSync(join(root, 'src', 'styles', 'tokens.generated.css'), buildCss());
  console.log('Theme tokens written to src/styles/tokens.generated.css');
}
